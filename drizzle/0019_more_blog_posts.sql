## Rule 1: If it is under warranty, claim first

Before anything else, check the warranty. A fault inside the warranty period should be repaired at no cost to you, so there is nothing to decide. Our [warranty expiry calculator](/tools/warranty-expiry-calculator) tells you where you stand, and our guide to [claiming an appliance warranty](/blog/how-to-claim-appliance-warranty-singapore-malaysia) explains the steps.

## Rule 2: The 50% rule

The most useful rule of thumb is simple: **if the repair costs half or more of a new appliance, replace it.** Paying half the price of a new one to keep an old one running is rarely good value, because the old unit has the same age and the same weak points as before.

## Rule 3: Look at the age

A repair makes sense when the appliance has plenty of life left. Compare its age with its typical lifespan, which is 10 to 15 years for a fridge, 8 to 12 for a washing machine or a split air-con, and 7 to 10 for a microwave or a television. Our [appliance lifespan checker](/tools/appliance-lifespan) shows where yours stands.

As a guide:

- **Under 60% of its lifespan**: repair unless the quote is very high.
- **Within its typical lifespan**: repair if the quote is cheap, replace if it is more than about a third of the new price.
- **Past its lifespan**: replace unless the repair is trivial, since another fault is likely soon.

## Rule 4: Count the running cost

Newer appliances are often far more efficient. An inverter air-con or a modern fridge can use a third less electricity than an old model. Try our [air-con electricity cost calculator](/tools/aircon-electricity-cost) to see what the running cost of your current unit adds up to over a year, and how much of a replacement an inverter would pay back.

## Rule 5: Price everything on both sides

Compare like with like. For the **repair**, include the call-out fee, parts and labour, and ask how long the repair itself is guaranteed. For the **replacement**, include delivery, installation, and removal of the old unit, and subtract any trade-in. Then ask one more question: how long will the repaired appliance realistically last, and what does that cost per year?

## Quick examples

- **A 3-year-old fridge, S$150 repair, S$1,200 new**: repair. It is young and the repair is 12% of a new one.
- **A 9-year-old washer, RM550 repair, RM1,400 new**: close call at 39%. If it has had other faults, replace.
- **A 13-year-old air-con, S$400 gas and compressor repair, S$1,100 new**: replace. It is past its lifespan and the repair is over a third of a new one.

