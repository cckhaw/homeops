## 1. Raise the thermostat by a degree or two

Each degree you raise the setting saves roughly **6% of the energy**. Many people are comfortable at 25 to 26°C, especially with a fan to move the air. Going from 22°C to 25°C is a sizeable saving over a year.

## 2. Add a fan

A ceiling or standing fan costs only a few cents an hour to run and makes the room feel several degrees cooler, so you can raise the air-con setting without feeling it.

## 3. Keep the filters clean

Wash the filters every two to four weeks. Clogged filters restrict airflow, so the compressor runs longer to cool the same room. It is a five-minute job that also helps air quality. Our guide to [how often to service your air-con](/blog/how-often-service-aircon-singapore-malaysia) has a full schedule.

## 4. Book regular servicing

A dirty indoor coil or outdoor unit and a low gas level all push consumption up. A regular general service and an occasional chemical wash keep the unit efficient and often prevent expensive breakdowns. See the typical yearly cost in our [air-con service cost calculator](/tools/aircon-service-cost).

## 5. Use the timer or sleep mode

Do not run the unit all night at full strength. Sleep mode raises the temperature gradually, and a timer switches the unit off once you are asleep or out. Both avoid cooling an empty or already-cool room.

## 6. Block the heat before it enters

Close curtains or blinds on sun-facing windows, keep doors and windows shut while cooling, and seal gaps. A room that gains less heat needs less cooling. Outdoor units in direct sun and with blocked airflow also work harder, so keep them shaded and clear.

## 7. Size the unit properly

An air-con that is too small runs flat out and never catches up. One that is too big cycles on and off, wastes energy and removes humidity poorly. Choose the capacity for the room size and how much sun it gets, and ask for advice before buying.

## 8. Choose an inverter model

Inverter units slow down instead of switching off, which holds the temperature and saves energy, often around 20 to 30% compared with an old non-inverter unit of the same size. If your air-con is old, compare the saving with the price: the [electricity cost calculator](/tools/aircon-electricity-cost) shows the yearly difference, and the [repair or replace calculator](/tools/repair-or-replace) helps you decide whether to fix or upgrade.

## 9. Switch it off when you leave

It is the oldest tip, and still the most effective. Cooling an empty room is wasted energy. If you will be out for more than 30 minutes or so, turn it off or use a timer.

