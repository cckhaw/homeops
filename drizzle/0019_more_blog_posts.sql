## Step 1: Check that you are still covered

First, work out the end date. Warranties normally start on the purchase or delivery date on your receipt and run for a fixed number of months. Our free [warranty expiry calculator](/tools/warranty-expiry-calculator) gives you the exact end date and the days left in a few seconds.

Read the warranty card too. Many brands cover **parts but not labour**, or give the compressor or motor a longer warranty than the rest of the appliance. Know which part of your product is covered before you call.

## Step 2: Gather what you will need

Have these ready before you contact anyone:

- **Proof of purchase**: the receipt or invoice, or a clear photo of it.
- **Model and serial number**: usually on the nameplate sticker at the back or inside the door.
- **The fault, described clearly**: what happens, when it started, and what you already tried.
- **Photos or a short video** showing the fault, with an error code if there is one.
- **The warranty card**, if the brand issued one.

If the receipt is lost, the retailer or your bank or card statement can sometimes help to prove the date. Do not wait until something breaks to find out.

## Step 3: Contact the right party

Usually you have two options: the **brand's service centre** or the **retailer** where you bought it. For big appliances the brand handles repairs under the manufacturer warranty. If the retailer sold you an extended plan, they are the contact for that. When unsure, start with the retailer, since they sold you the product and can point you to the right service channel.

Always report the fault **in writing** (e-mail or the brand's online form), even if you also phone. A written record with a date protects you if the warranty is about to end.

## Step 4: Do not repair it yourself first

Unauthorised repairs commonly void the warranty. Do not open the appliance, and do not let a third-party technician work on it before the brand has looked at it. Switch it off if it is unsafe, and take photos of the current state.

## Step 5: Keep a paper trail

Note the date, the person you spoke with, and any reference number. Keep the job sheet after a visit. If the same fault returns, that history matters: repeated repairs for the same problem can support a request for a replacement or refund.

## If the claim is refused

Stay polite and ask for the reason **in writing**. Then check it against the warranty terms. If you think the refusal is wrong:

1. Escalate to the brand's customer care manager or head office.
2. Contact the retailer, who may have their own obligations to you as the seller.
3. In Singapore, the consumer association CASE can advise and mediate. In Malaysia, you can seek advice from the Ministry of Domestic Trade and Costs of Living and, for qualifying claims, the Tribunal for Consumer Claims.

Consumer rules differ and change, so treat this as a starting point and confirm the current position with the relevant authority.

